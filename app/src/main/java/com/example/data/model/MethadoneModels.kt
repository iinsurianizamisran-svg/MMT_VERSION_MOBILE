package com.example.data.model

enum class RegimenType(val label: String, val description: String) {
    DOT("DOT Sahaja", "Directly Observed Therapy - Hadir setiap hari di klinik"),
    DOT_DBB("DOT & DBB", "Directly Observed Therapy + Dos Bawa Balik (Take-Home)")
}

enum class TreatmentPhase(val label: String) {
    INDUKSI("Fasa Induksi (1-14 Hari)"),
    PENSTABILAN("Fasa Penstabilan"),
    PENGEKALAN("Fasa Pengekalan (Maintenance)")
}

enum class PatientStatus(val label: String) {
    AKTIF("Aktif"),
    DITANGGUHKAN("Ditangguhkan"),
    SELESAI("Selesai Rawatan")
}

enum class DispensationStatus(val label: String) {
    HADIR_DOT("Hadir DOT (Minum Depan Staf)"),
    HADIR_DOT_DBB("Hadir DOT + Bekalan DBB"),
    TIDAK_HADIR_MISSED("Tidak Hadir (Missed Dose)"),
    DITANGGUH_KLINIKAL("Ditangguh Atas Sebab Klinikal")
}

enum class AppointmentType(val label: String, val intervalDays: Int) {
    SEMAKAN_DOKTOR("Semakan Dos & Penilaian Doktor", 30),
    UJIAN_UDS("Ujian Saringan Urin (UDS)", 30),
    PENILAIAN_DBB("Penilaian Kelayakan DBB", 60),
    KAUNSELING("Sesi Kaunseling Kepatuhan", 14)
}

enum class AppointmentStatus(val label: String) {
    AKAN_DATANG("Akan Datang"),
    SELESAI("Selesai"),
    TERTUNGGAK("Tertunggak (Overdue)"),
    DIBATALKAN("Dibatalkan")
}

enum class AlertSeverity(val label: String) {
    KRITIKAL("Kritikal (Toleransi Opioid Jatuh)"),
    AMARAN_SEDERHANA("Amaran Kepatuhan"),
    PERINGATAN("Peringatan Klinikal")
}

data class Patient(
    val id: String,
    val regNumber: String,
    val fullName: String,
    val icNumber: String,
    val age: Int,
    val phone: String,
    val emergencyContact: String,
    val startDate: String,
    val regimen: RegimenType,
    val currentDoseMg: Double,
    val phase: TreatmentPhase,
    val status: PatientStatus,
    val dbbDaysAllowed: Int = 0, // e.g. 1 to 6 days
    val lastUdsDate: String = "",
    val lastUdsResult: String = "Negatif", // Negatif, Positif Opiat, Positif THC, dsb.
    val notes: String = ""
) {
    val doseInMl: Double get() = currentDoseMg / 5.0 // Metadon Sirap lazim KKM 5mg/ml
}

data class DispensationRecord(
    val id: String,
    val patientId: String,
    val patientName: String,
    val date: String, // YYYY-MM-DD
    val timestamp: Long,
    val status: DispensationStatus,
    val dotDoseMg: Double,
    val dbbDoseMg: Double = 0.0,
    val dbbDaysGiven: Int = 0,
    val dispenserName: String = "Pegawai Farmasi",
    val staffNotes: String = ""
)

data class FollowUpAppointment(
    val id: String,
    val patientId: String,
    val patientName: String,
    val regNumber: String,
    val appointmentType: AppointmentType,
    val scheduledDate: String, // YYYY-MM-DD
    val scheduledTime: String = "09:00 AM",
    val status: AppointmentStatus = AppointmentStatus.AKAN_DATANG,
    val doctorNotes: String = "",
    val isAutoGenerated: Boolean = true
)

data class ClinicalAlert(
    val id: String,
    val patientId: String,
    val patientName: String,
    val regNumber: String,
    val severity: AlertSeverity,
    val title: String,
    val message: String,
    val protocolAction: String,
    val consecutiveMissedDays: Int = 0
)

data class AdherenceStats(
    val totalActivePatients: Int,
    val dotCount: Int,
    val dotDbbCount: Int,
    val overallAdherenceRate: Float, // 0..100
    val todayPresentCount: Int,
    val todayMissedCount: Int,
    val todayPendingCount: Int,
    val highRiskPatientsCount: Int,
    val dailyTrend: List<Pair<String, Float>> = emptyList() // Date to % Adherence
)

// --- Doctor Follow-Up Frequency Parameters & Auto-Scheduling Engine ---

data class DoctorSchedulingConfig(
    val inductionIntervalDays: Int = 7,       // Fasa Induksi: Semakan setiap 7 hari (1-14 hari awal)
    val stabilizationIntervalDays: Int = 14,  // Fasa Penstabilan: Semakan setiap 14 hari
    val maintenanceIntervalDays: Int = 30,    // Fasa Pengekalan: Semakan setiap 30 hari
    val udsIntervalDays: Int = 30,            // Ujian UDS berkala: Setiap 30 hari
    val dbbAuditIntervalDays: Int = 60,       // Audit kelayakan DBB: Setiap 60 hari
    val highRiskIntervalDays: Int = 3,        // Pesakit berisiko tinggi (missed / UDS positif): Setiap 3 hari
    val autoSuggestEnabled: Boolean = true
)

data class SuggestedAppointment(
    val id: String,
    val patientId: String,
    val patientName: String,
    val regNumber: String,
    val appointmentType: AppointmentType,
    val suggestedDate: String, // YYYY-MM-DD
    val suggestedTime: String = "09:30 AM",
    val rationale: String,
    val priority: AlertSeverity,
    val isAlreadyScheduled: Boolean = false
)

// --- Comprehensive Doctor Dashboard KPIs ---

data class DispensingTrendPoint(
    val label: String,
    val dotMg: Float,
    val dbbMg: Float,
    val totalMg: Float = dotMg + dbbMg
)

data class DoctorDashboardAnalytics(
    // 1. Patient Adherence Rates
    val overallAdherenceRate: Float,
    val dotAdherenceRate: Float,
    val dotDbbAdherenceRate: Float,
    val adherenceTrend: List<Pair<String, Float>>,

    // 2. Medication Dispensing Trends
    val todayTotalVolumeMg: Double,
    val todayDotDoseMg: Double,
    val todayDbbDoseMg: Double,
    val dispensingVolumeTrend: List<DispensingTrendPoint>,

    // 3. Appointment No-Show Rates
    val totalAppointments: Int,
    val attendedAppointmentsCount: Int,
    val noShowAppointmentsCount: Int,
    val noShowRate: Float, // % no-show
    val upcomingAppointmentsCount: Int,
    val noShowTrend: List<Pair<String, Float>>,

    // 4. Treatment Effectiveness Over Time
    val retentionRate: Float, // % active >= 6 months
    val cleanUdsRate: Float, // % negative UDS
    val udsTrend: List<Pair<String, Float>>,
    val stabilizedDoseRate: Float, // % with steady dose
    val treatmentEffectivenessIndex: Float // 0..100 composite score
)

