package com.example.data.local

import androidx.room.Entity
import androidx.room.PrimaryKey
import com.example.data.model.AppointmentStatus
import com.example.data.model.AppointmentType
import com.example.data.model.DispensationRecord
import com.example.data.model.DispensationStatus
import com.example.data.model.FollowUpAppointment
import com.example.data.model.Patient
import com.example.data.model.PatientStatus
import com.example.data.model.RegimenType
import com.example.data.model.TreatmentPhase

@Entity(tableName = "patients")
data class PatientEntity(
    @PrimaryKey val id: String,
    val regNumber: String,
    val fullName: String,
    val icNumber: String,
    val age: Int,
    val phone: String,
    val emergencyContact: String,
    val startDate: String,
    val regimen: RegimenType,
    val currentDoseMg: Double,
    val phase: TreatmentPhase,
    val status: PatientStatus,
    val dbbDaysAllowed: Int,
    val lastUdsDate: String,
    val lastUdsResult: String,
    val notes: String
)

@Entity(tableName = "dispensations")
data class DispensationEntity(
    @PrimaryKey val id: String,
    val patientId: String,
    val patientName: String,
    val date: String,
    val timestamp: Long,
    val status: DispensationStatus,
    val dotDoseMg: Double,
    val dbbDoseMg: Double,
    val dbbDaysGiven: Int,
    val dispenserName: String,
    val staffNotes: String
)

@Entity(tableName = "appointments")
data class AppointmentEntity(
    @PrimaryKey val id: String,
    val patientId: String,
    val patientName: String,
    val regNumber: String,
    val appointmentType: AppointmentType,
    val scheduledDate: String,
    val scheduledTime: String,
    val status: AppointmentStatus,
    val doctorNotes: String,
    val isAutoGenerated: Boolean
)

// Mapping extensions
fun PatientEntity.toDomain() = Patient(
    id = id,
    regNumber = regNumber,
    fullName = fullName,
    icNumber = icNumber,
    age = age,
    phone = phone,
    emergencyContact = emergencyContact,
    startDate = startDate,
    regimen = regimen,
    currentDoseMg = currentDoseMg,
    phase = phase,
    status = status,
    dbbDaysAllowed = dbbDaysAllowed,
    lastUdsDate = lastUdsDate,
    lastUdsResult = lastUdsResult,
    notes = notes
)

fun Patient.toEntity() = PatientEntity(
    id = id,
    regNumber = regNumber,
    fullName = fullName,
    icNumber = icNumber,
    age = age,
    phone = phone,
    emergencyContact = emergencyContact,
    startDate = startDate,
    regimen = regimen,
    currentDoseMg = currentDoseMg,
    phase = phase,
    status = status,
    dbbDaysAllowed = dbbDaysAllowed,
    lastUdsDate = lastUdsDate,
    lastUdsResult = lastUdsResult,
    notes = notes
)

fun DispensationEntity.toDomain() = DispensationRecord(
    id = id,
